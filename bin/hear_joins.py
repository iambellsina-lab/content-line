# The cut list, read as joins rather than as clips
# ---------------------------------------------------------------------------


@dataclass
class Join:
    number: int                 # the segment boundary: join 3 is between segment 3 and 4
    out_at: float               # source seconds where the first segment leaves off
    in_at: float                # source seconds where the next one comes in
    # The two segments this sits between, carried rather than looked up. Two segments
    # of one clip can share an end time, and matching a boundary back to a segment by
    # its timestamp picked the wrong one.
    seg_before: tuple[float, float] = (0.0, 0.0)
    seg_after: tuple[float, float] = (0.0, 0.0)
    tail: tuple[float, float] = (0.0, 0.0)
    head: tuple[float, float] = (0.0, 0.0)
    before: str = ""
    after: str = ""
    continuous: bool = False    # the tape runs straight through, so there is no cut
    skip: bool = False          # not exported, for whatever reason
    notes: list[str] = field(default_factory=list)

    @property
    def listen_seconds(self) -> float:
        return round((self.tail[1] - self.tail[0]) + (self.head[1] - self.head[0]), 3)

    @property
    def gap(self) -> float:
        return round(self.in_at - self.out_at, 3)


@dataclass
class Clip:
    name: str
    segments: list[tuple[float, float]]
    joins: list[Join] = field(default_factory=list)

    @property
    def to_hear(self) -> list[Join]:
        return [j for j in self.joins if not j.skip]


def _float(value, what: str) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        die(f"{what} must be a number, got {value!r}")
    return 0.0


def read_clips(spec: dict, src_len: float | None) -> list[Clip]:
    raw_pieces = spec.get("pieces")
    if raw_pieces is None:
        raw_pieces = [spec]                     # a one piece spec is a batch of one
    if not isinstance(raw_pieces, list) or not raw_pieces:
        die("'pieces' must be a non-empty list. A single piece cut list works too: "
            "this reads the whole file as one piece when there is no 'pieces' key.")
    clips: list[Clip] = []
    for i, raw in enumerate(raw_pieces):
        if not isinstance(raw, dict):
            die(f"piece {i} must be a JSON object")
        name = str(raw.get("piece") or raw.get("name") or raw.get("filename")
                   or f"piece{i + 1}")
        raw_segs = raw.get("segments")
        if not isinstance(raw_segs, list) or not raw_segs:
            die(f"piece {name!r} needs a non-empty 'segments' list. Each entry is "
                '{"start": seconds, "end": seconds}; every other key in it is ignored, '
                "so a cut list carrying its own notes is read as it stands.")
        segs: list[tuple[float, float]] = []
        texts: list[str] = []
        for k, seg in enumerate(raw_segs):
            if not isinstance(seg, dict) or "start" not in seg or "end" not in seg:
                die(f"piece {name!r} segment {k} needs 'start' and 'end' in seconds")
            a = _float(seg["start"], f"{name} segment {k} start")
            b = _float(seg["end"], f"{name} segment {k} end")
            if b <= a:
                die(f"piece {name!r} segment {k} ends before it starts: {a} to {b}")
            if src_len is not None and a >= src_len:
                die(f"piece {name!r} segment {k} starts at {a:.2f}s, past the end of "
                    f"the source ({src_len:.2f}s). Wrong source, or wrong cut list.")
            if src_len is not None and b > src_len + 0.05:
                warn(f"piece {name!r} segment {k} ends at {b:.2f}s, past the source end "
                     f"({src_len:.2f}s), clamped")
                b = src_len
            segs.append((round(a, 3), round(b, 3)))
            texts.append(str(seg.get("text") or ""))
        clip = Clip(name=name, segments=segs)
        for k in range(len(segs) - 1):
            clip.joins.append(Join(number=k + 1, out_at=segs[k][1], in_at=segs[k + 1][0],
                                   seg_before=segs[k], seg_after=segs[k + 1],
                                   before=tail_of(texts[k]), after=head_of(texts[k + 1])))
        clips.append(clip)
    return clips


def measure_joins(clip: Clip, pad: float, src_len: float | None,
                  cues: list[dict] | None, keep_continuous: bool) -> None:
    for j in clip.joins:
        # Clamped to the segment, never past its own in-point or out-point. Past it is
        # tape the finished piece cuts away, and listening to that is listening to a
        # join that will never play.
        tail_a = max(j.seg_before[0], j.out_at - pad)
        tail_b = j.out_at
        head_a = j.in_at
        head_b = min(j.seg_after[1], j.in_at + pad)
        if src_len is not None:
            tail_a, tail_b = max(0.0, tail_a), min(src_len, tail_b)
            head_a, head_b = max(0.0, head_a), min(src_len, head_b)
        j.tail, j.head = (round(tail_a, 3), round(tail_b, 3)), (round(head_a, 3), round(head_b, 3))

        if tail_b - tail_a < pad - 0.01:
            j.notes.append(f"tail clamped to {tail_b - tail_a:.2f}s, the segment before "
                           "is shorter than the pad")
        if head_b - head_a < pad - 0.01:
            j.notes.append(f"head clamped to {head_b - head_a:.2f}s, the segment after "
                           "is shorter than the pad")
        if tail_b - tail_a < MIN_WINDOW or head_b - head_a < MIN_WINDOW:
            j.notes.append("one side of this join is shorter than "
                           f"{MIN_WINDOW:.2f}s, which is a click rather than a listen. "
                           "Not exported")
            j.skip = True
            continue

        j.continuous = abs(j.gap) <= CONTINUOUS_TOLERANCE
        if j.continuous:
            j.notes.append("the tape runs straight through here, so there is no cut "
                           "to hear")
            j.skip = not keep_continuous
        elif j.gap < 0:
            j.notes.append(f"this join reaches BACK {abs(j.gap):.2f}s in the recording. "
                           "The second half was said before the first half, which is "
                           "the whole reason this kit assembles in edit order, and it "
                           "is the kind of join most likely to need a trim")

        if cues:
            j.before = words_before(cues, j.out_at) or j.before
            j.after = words_after(cues, j.in_at) or j.after


