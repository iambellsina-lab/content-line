def tts_command(text: str, out_wav: Path) -> tuple[list[str], Path] | None:
    """A voice the machine already has, or nothing. Nothing is downloaded here."""
    if shutil.which("say"):                                         # macOS
        aiff = out_wav.with_suffix(".aiff")
        return (["say", "-o", str(aiff), text], aiff)
    for exe in ("espeak-ng", "espeak"):                             # Linux
        if shutil.which(exe):
            return ([exe, "-w", str(out_wav), text], out_wav)
    if IS_WINDOWS and shutil.which("powershell"):
        script = ("Add-Type -AssemblyName System.Speech; "
                  "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer; "
                  f"$s.SetOutputToWaveFile('{out_wav}'); $s.Speak('{text}'); $s.Dispose()")
        return (["powershell", "-NoProfile", "-Command", script], out_wav)
    return None


def tts_available() -> bool:
    return tts_command("1", Path(tempfile.gettempdir()) / "_probe.wav") is not None


NUMBER_WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven",
                "eight", "nine", "ten", "eleven", "twelve"]


def spoken(n: int) -> str:
    return NUMBER_WORDS[n] if 0 <= n < len(NUMBER_WORDS) else str(n)


def build_marker(n: int, mode: str, workdir: Path) -> Path | None:
    """One WAV per join number, built once and reused across clips."""
    if mode == "none":
        return None
    out = workdir / f"marker-{mode}-{n}.wav"
    if out.exists():
        return out
    ff = ffmpeg_bin()
    sine = f"sine=frequency={BEEP_HZ}:sample_rate={SAMPLE_RATE}"

    if mode == "speech":
        voice_raw = workdir / f"voice-{n}.wav"
        cmd = tts_command(spoken(n), voice_raw)
        if cmd is None:
            return None
        made = subprocess.run(cmd[0], capture_output=True, text=True)
        if made.returncode != 0 or not cmd[1].exists():
            warn(f"the system voice would not render {spoken(n)!r}, falling back to beeps "
                 f"for this marker: {made.stderr.strip()[:200]}")
            return build_marker(n, "tone", workdir)
        run_ff([ff, "-y", "-hide_banner", "-loglevel", "error",
                "-f", "lavfi", "-t", f"{BEEP_LEN:.3f}", "-i", sine,
                "-i", str(cmd[1]),
                "-filter_complex",
                f"[0:a]{AUDIO_FMT},volume={BEEP_LEVEL}[b];"
                f"[1:a]{AUDIO_FMT}[s];"
                f"[b][s]concat=n=2:v=0:a=1,"
                f"adelay={int(LEAD_SILENCE * 1000)}|{int(LEAD_SILENCE * 1000)},"
                f"apad=pad_dur={TAIL_SILENCE},{AUDIO_FMT}[m]",
                "-map", "[m]", "-c:a", "pcm_s16le", "-ar", str(SAMPLE_RATE),
                "-ac", "2", str(out)], f"building the spoken marker for join {n}")
        return out

    # tone: n beeps. One lavfi input each, because reusing one input stream n times
    # needs an asplit and n inputs is plainer to read when it goes wrong.
    args: list[str] = []
    chain: list[str] = []
    labels = ""
    count = max(1, n)
    for i in range(count):
        args += ["-f", "lavfi", "-t", f"{BEEP_LEN:.3f}", "-i", sine]
        chain.append(f"[{i}:a]{AUDIO_FMT},volume={BEEP_LEVEL},"
                     f"apad=pad_dur={BEEP_GAP}[b{i}]")
        labels += f"[b{i}]"
    chain.append(f"{labels}concat=n={count}:v=0:a=1,"
                 f"adelay={int(LEAD_SILENCE * 1000)}|{int(LEAD_SILENCE * 1000)},"
                 f"apad=pad_dur={TAIL_SILENCE},{AUDIO_FMT}[m]")
    run_ff([ff, "-y", "-hide_banner", "-loglevel", "error"] + args +
           ["-filter_complex", ";".join(chain), "-map", "[m]",
            "-c:a", "pcm_s16le", "-ar", str(SAMPLE_RATE), "-ac", "2", str(out)],
           f"building the tone marker for join {n}")
    return out


def wav_seconds(path: Path) -> float:
    raw = subprocess.run([ffprobe_bin(), "-v", "error", "-show_entries",
                          "format=duration", "-of", "csv=p=0", str(path)],
                         capture_output=True, text=True)
    try:
        return float((raw.stdout or "0").strip() or 0)
    except ValueError:
        return 0.5


