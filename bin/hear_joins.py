def main() -> None:
    ap = argparse.ArgumentParser(
        description="Export only the joins of a cut list, so somebody hears the cuts "
                    "rather than the clip. Ten joins is a short listen, and no other "
                    "step in this kit has heard anything.",
        epilog="Run this BEFORE assemble_clip.py. A join that reads cleanly can still "
               "sound like a cut, and that is only findable by ear.")
    ap.add_argument("cuts", help="path to the JSON cut list, as bin/plan_clips.py writes it")
    ap.add_argument("--source", help="the long recording. Needed when the cut list does "
                                     "not name one, which a hand-assembled list often "
                                     "does not")
    ap.add_argument("--transcript", help="an .srt or .cues.json, for the words either "
                                         "side of each cut. Without it the words come "
                                         "from the cut list's own segment text")
    ap.add_argument("--pad", type=float, default=DEFAULT_PAD,
                    help=f"seconds either side of each cut (default {DEFAULT_PAD}). "
                         "Two either side is four seconds per join, so --pad 1.0 is "
                         "how ten joins becomes a twenty second listen")
    ap.add_argument("--out-dir", help="where the listen files go (default: a 'joins' "
                                      "folder beside the cut list)")
    ap.add_argument("--only", action="append", default=[],
                    help="just the clips whose name contains this. Repeatable")
    ap.add_argument("--marker", choices=("auto", "speech", "tone", "none"), default="auto",
                    help="how each join is announced: 'speech' says the join number, "
                         "'tone' beeps it, 'none' butts the joins together with nothing "
                         "between. 'auto' (the default) uses speech when the machine "
                         "already has a voice and beeps when it does not")
    ap.add_argument("--video", action="store_true",
                    help="also export a small video of the same joins, for cuts that "
                         "fail with the eyes rather than the ears")
    ap.add_argument("--frame", choices=("vertical", "source"), default="vertical",
                    help="with --video: 'vertical' is the 9 by 16 delivery crop at a "
                         "third of delivery size, 'source' is the whole picture")
    ap.add_argument("--style", help="with --video: a style file, read only for zoom, "
                                    "focus_x and focus_y so the crop matches the render")
    ap.add_argument("--all-joins", action="store_true",
                    help="include the boundaries where the tape runs straight through. "
                         "They are skipped by default because there is no cut to hear")
    ap.add_argument("--list", dest="list_only", action="store_true",
                    help="print the table and the listening time, read no media, "
                         "write nothing")
    ap.add_argument("--json", dest="json_out",
                    help="also write the join table as JSON, for a later step that "
                         "wants to know which joins were exported")
    args = ap.parse_args()

    if args.pad <= 0:
        die("--pad must be more than zero. It is the seconds either side of each cut, "
            "and zero of them is silence.")

    cuts_path = Path(args.cuts).expanduser()
    spec = read_json(cuts_path, "cut list")
    if not isinstance(spec, dict):
        die(f"{cuts_path} must be a JSON object, a block that starts with {{ and ends "
            "with }}. bin/plan_clips.py writes one.")
    cuts_dir = cuts_path.resolve().parent

    # ---- the source, which is the one thing a cut list does not always carry
    src: Path | None = None
    info: dict = {"duration": None, "width": 0, "height": 0}
    if not args.list_only:
        named = args.source or spec.get("source")
        if not named:
            die(f"{cuts_path.name} does not name a \"source\", so there is nothing to "
                "listen to.\n"
                "  Pass --source with the long recording this was cut from, or add\n"
                '  "source": "path/to/recording.mov" to the cut list.\n'
                "  --list prints the join table without any media, if that is all you need.")
        src = resolve_input(str(named), cuts_dir if not args.source else Path.cwd())
        if not src.exists():
            die(f"source not found: {src}\n"
                f"  Looked next to the cut list and in {Path.cwd()}.")
        info = probe_source(src)
        if not info["has_audio"]:
            die(f"{src.name} has no audio track. The whole point here is the sound of "
                "a join, so there is nothing this can tell you about it.")
        if args.video and not info["has_video"]:
            die(f"{src.name} has no video track, so --video has nothing to show. "
                "Run it without --video.")
        # Only the filters this tool actually uses. Asking for one it does not use
        # would fail a thin build for no reason.
        need = ["concat", "aformat", "atrim", "asetpts"]
        if args.marker != "none":
            need += ["sine", "apad", "adelay"]
        if args.video:
            need += ["color", "trim", "setpts", "scale", "crop", "fps"]
        thin = [f for f in need if not has_filter(f)]
        if thin:
            die(f"this ffmpeg build is missing: {', '.join(thin)}.\n"
                "  Install a full ffmpeg build. macOS: brew install ffmpeg. "
                "Debian or Ubuntu: sudo apt install ffmpeg.")

    # ---- the clips, and their joins
    clips = read_clips(spec, info["duration"])
    cues: list[dict] | None = None
    word_source = "the cut list's own segment text"
    if args.transcript:
        tpath = resolve_input(args.transcript, Path.cwd())
        cues = load_transcript(tpath)
        word_source = f"the transcript {tpath}"
    for clip in clips:
        measure_joins(clip, args.pad, info["duration"], cues, args.all_joins)

    if args.only:
        clips = [c for c in clips if any(o.lower() in c.name.lower() for o in args.only)]
        if not clips:
            die("--only matched no clip in this cut list")

    # ---- the marker, decided once and said out loud
    mode = args.marker
    marker_said = ""
    if mode == "auto":
        if tts_available():
            mode, marker_said = "speech", "the join number spoken by this machine's own voice"
        else:
            mode, marker_said = "tone", ("N beeps for join N, generated by ffmpeg, "
                                         "because no system voice was found")
    elif mode == "speech":
        if not tts_available():
            warn("no system voice found (macOS `say`, Linux `espeak-ng`, Windows SAPI), "
                 "falling back to beeps")
            mode, marker_said = "tone", "N beeps for join N (no system voice found)"
        else:
            marker_said = "the join number spoken by this machine's own voice"
    elif mode == "tone":
        marker_said = "N beeps for join N, generated by ffmpeg"
    else:
        marker_said = "nothing between the joins, as asked"

    # ---- the header, so the listening budget is known before anything is encoded
    hear_total = sum(len(c.to_hear) for c in clips)
    seconds_total = round(sum(j.listen_seconds for c in clips for j in c.to_hear), 1)
    boundary_total = sum(len(c.joins) for c in clips)
    continuous_total = sum(1 for c in clips for j in c.joins if j.continuous)
    real_cuts = boundary_total - continuous_total
    say(f"{plural(len(clips), 'clip')}, {plural(boundary_total, 'segment boundary')}, "
        f"{real_cuts} of them an actual cut in the tape")
    say(f"  exporting {plural(hear_total, 'join')}, {seconds_total:.1f}s of tape at "
        f"{args.pad:.1f}s either side")
    skipped_continuous = sum(1 for c in clips for j in c.joins if j.continuous and j.skip)
    other_skips = (boundary_total - hear_total) - skipped_continuous
    if skipped_continuous:
        say(f"  {skipped_continuous} boundaries skipped: the tape runs straight through "
            "them, so there is no cut there. --all-joins keeps them")
    elif continuous_total and args.all_joins:
        say(f"  {continuous_total} of those are continuous tape with no cut in them, "
            "kept because --all-joins was given")
    if other_skips > 0:
        say(f"  {other_skips} more skipped because one side was too short to hear. "
            "The printed list says which")
    say(f"  words from {word_source}")
    say(f"  markers: {marker_said}")
    if src is not None:
        say(f"  source {src.name}  {info['duration']:.2f}s"
            + (f"  {info['width']}x{info['height']}" if info["has_video"] else "  audio only"))
    say()

    for clip in clips:
        print_clip(clip, args.pad)
        say()

    table = {
        "_help": "The joins hear_joins.py found in this cut list. 'skipped' means the "
                 "tape runs straight through that boundary, so there is no cut to hear.",
        "_by": TOOL,
        "cut_list": str(cuts_path),
        "pad_seconds": args.pad,
        "marker": mode,
        "clips": [{
            "clip": c.name,
            "segments": len(c.segments),
            "joins": [{
                "join": j.number, "out_at": j.out_at, "in_at": j.in_at,
                "gap": j.gap, "listen_seconds": j.listen_seconds,
                "continuous_tape": j.continuous, "skipped": j.skip,
                "before": j.before, "after": j.after,
                "notes": j.notes,
            } for j in c.joins],
        } for c in clips],
    }

    if args.list_only:
        say("Listed only. Nothing was read from the media and nothing was written.")
        if args.json_out:
            Path(args.json_out).expanduser().write_text(
                json.dumps(table, indent=2) + "\n", encoding="utf-8")
            say(f"join table -> {args.json_out}")
        return

    if not hear_total:
        say("No cut in this list needs hearing: every boundary is continuous tape. "
            "Nothing was exported. --all-joins exports them anyway.")
        return

    out_dir = Path(args.out_dir).expanduser() if args.out_dir else (cuts_dir / "joins")
    out_dir.mkdir(parents=True, exist_ok=True)

    style: dict = {}
    if args.style:
        spath = resolve_input(args.style, Path.cwd())
        loaded = read_json(spath, "style file")
        style = loaded if isinstance(loaded, dict) else {}
    vsteps: list[str] = []
    size = (VERTICAL_W, VERTICAL_H)
    if args.video:
        size0, size1, vsteps = video_frame(info, args.frame, style)
        size = (size0, size1)

    with tempfile.TemporaryDirectory(prefix="hear-joins-") as tmp:
        workdir = Path(tmp)
        markers: dict[int, Path | None] = {}
        for clip in clips:
            for j in clip.to_hear:
                if j.number not in markers:
                    markers[j.number] = build_marker(j.number, mode, workdir)

        marker_seconds = {n: (wav_seconds(path) if path else 0.0)
                          for n, path in markers.items()}

        written: list[tuple[str, Path, dict]] = []
        for clip in clips:
            if not clip.to_hear:
                say(f"{clip.name}: every boundary is continuous tape, nothing exported")
                continue
            # What the file SHOULD be, worked out before it is written, so a short
            # window cannot pass unnoticed. The first version of this tool bounded
            # each window with an input `-t` and lost up to 0.42s off the end of a
            # 2.00s tail, which is exactly the fraction of a second a listener is
            # trying to judge. Checked rather than trusted, every run.
            expected = round(sum(j.listen_seconds for j in clip.to_hear)
                             + sum(marker_seconds.get(j.number, 0.0)
                                   for j in clip.to_hear), 3)
            stem = f"{slug(clip.name, 'clip')}-joins"
            for want_video, suffix in ((False, ".m4a"),) + (
                    ((True, ".mp4"),) if args.video else ()):
                out_path = out_dir / f"{stem}{suffix}"
                export_clip(clip, src, out_path, markers, want_video,
                            vsteps if want_video else [], size)
                got = probe_result(out_path)
                drift = got["seconds"] - expected
                if abs(drift) > 0.25:
                    warn(f"{clip.name}: {out_path.name} came out {got['seconds']:.2f}s "
                         f"and the windows plus markers add up to {expected:.2f}s, a "
                         f"{drift:+.2f}s difference. Something trimmed or padded a "
                         "window, so do not trust this file to be the join the "
                         "renderer will make. Check it against the printed table "
                         "before acting on what you hear.")
                got["expected"] = expected
                got["is_listen"] = not want_video
                written.append((clip.name, out_path, got))

    say("Written, and measured rather than assumed:")
    total_bytes = 0
    listen_seconds = 0.0
    for name, path, got in written:
        say(f"  {name:<18} {got['seconds']:6.2f}s  {human_bytes(got['bytes']):>9}  "
            f"(planned {got['expected']:.2f}s)  {path}")
        total_bytes += got["bytes"]
        if got["is_listen"]:
            listen_seconds += got["seconds"]
    # The listening time counts the audio files once. A --video export is the SAME
    # joins again, so adding its length would double count what a person sits through.
    say(f"  {plural(len(written), 'file')}, {human_bytes(total_bytes)}, "
        f"{listen_seconds:.2f}s to listen to"
        + ("  (the videos are the same joins, not more of them)" if args.video else ""))

    if args.json_out:
        for entry in table["clips"]:
            entry["exported"] = [str(p) for n, p, _ in written if n == entry["clip"]]
        Path(args.json_out).expanduser().write_text(
            json.dumps(table, indent=2) + "\n", encoding="utf-8")
        say(f"  join table -> {args.json_out}")

    opener = "open" if sys.platform == "darwin" else ("start" if IS_WINDOWS else "xdg-open")
    say()
    say(f"Now listen to them. {opener} {out_dir}")
    say("This tool has not heard a single one of these files and cannot. It read "
        "timestamps and ran ffmpeg.")
    say("What it bought you is that hearing every cut in this batch is "
        f"{listen_seconds:.0f} seconds instead of re-watching every clip.")
    say("Where the audio disagrees with the plan, the audio wins: fix the cut list, "
        "run this again, and only then render.")


if __name__ == "__main__":
    main()
