#!/usr/bin/env python3
"""
hear_joins.py: export only the joins, so somebody actually hears the cuts.

THE GAP THIS FILLS. Every other planning tool in this kit reads text. plan_clips.py
decides where a clip starts, which segments it keeps and what order they play in, and
it decides all of that from a transcript. A join that reads cleanly on the page can
still sound like a cut: a breath sliced in half, a word clipped at the in-point, two
different room levels butted together, a sentence that lands on an upward inflection
and is answered by another upward inflection. None of that is in a transcript, and
none of it can be reasoned about. It has to be heard.

Measured on this kit's own four clip fixture on 2026-10-08: the finished clips are
143.6 seconds of video and their eight joins are 39.7 seconds of audio. A join is two
seconds either side of one instant, and everything else in a clip is tape that already
played in one piece and does not need checking. So this tool throws away the clip and
keeps the joins.

WHAT IT DOES:
  1. reads a cut list (the shape plan_clips.py writes, or a hand-written one)
  2. finds every boundary between consecutive segments
  3. drops the boundaries where the tape is continuous, because there is no cut there
     to hear. Those are the single biggest saving: on a real six piece batch, 53
     boundaries came down to 33 actual cuts
  4. takes N seconds of the tail of one segment and N seconds of the head of the next,
     and butts them together the way the renderer will
  5. writes ONE file per clip holding all of that clip's joins in order, with a marker
     between them saying which join you are on
  6. prints a numbered list: the two source timestamps, and the words on each side

HOW THE JOINS ARE MARKED, and why. Two modes, and the default picks between them:

  "speech"  a short beep, then the join number spoken ("three"), then a beat of
            silence. This is the default WHERE THE OPERATING SYSTEM ALREADY HAS A
            VOICE: macOS `say`, Linux `espeak-ng` or `espeak`, Windows SAPI through
            PowerShell. Nothing is downloaded and nothing is paid for. A number said
            out loud needs no counting, which matters on a thirteen segment piece.

  "tone"    N short beeps for join N, then a beat of silence. Generated by ffmpeg's
            own `sine` source, so it is identical on every machine and needs no voice
            installed. This is the fallback, and the right choice on a machine with no
            TTS or with a voice you would rather not hear. Two costs, both measured on
            a nine join fixture on 2026-10-08: counting nine beeps is tedious, and the
            markers came to 7.8 seconds against 14.0 seconds of tape, because join nine
            is nine beeps long. Spoken numbers stay flat at about 0.9s each.

  --marker speech | tone | none  forces one. The tool prints which one it used.

The join NUMBER is the segment boundary it sits on: join 3 is between segment 3 and
segment 4. It is not renumbered when continuous boundaries are dropped, so the number
you hear is the number in the printed list and in the cut list, and a note in the
printed list says which numbers were dropped.

THE ARITHMETIC, said plainly, because ROADMAP.md item 1 states it as twenty seconds
and that does not add up. Two seconds either side is FOUR seconds per join, so ten joins is about forty seconds
of tape plus markers, not twenty. If twenty seconds is the budget, `--pad 1.0` is how
you get it, and one second either side is still enough to hear a clipped word or a
room level change. The tool prints the tape total before it encodes anything, and the
measured length of every file it wrote afterwards, so the number is in front of you
rather than discovered later.

The other half of that budget is free. A boundary where the tape runs straight through
is not a cut, and plan_clips.py produces a lot of them, because a clip is usually a
few runs of consecutive sentences rather than a sentence at a time. Measured on a real
six piece batch on 2026-10-08: 53 segment boundaries, of which 20 were continuous tape
and 33 were actual cuts. Those 20 are skipped by default and listed as skipped, so
nothing is hidden and nothing is listened to twice.

WHAT IT IS FAITHFUL TO, and where it is not:
  - It reads the audio stream the renderer reads: `a:0` explicitly, because a phone
    file can carry an ordinary AAC track and a spatial one, and taking "the audio"
    can hand you the other one.
  - It seeks on the input exactly as assemble_clip.py does, so a join from minute 47
    of a 2.85 GB file does not decode 47 minutes first.
  - The two windows are butted with no crossfade and no gap, which is what the
    concat in the renderer does.
  - The pad is CLAMPED to the segment. If a segment is 1.2 seconds long, you get 1.2
    seconds, never 2, because the other 0.8 would be tape the finished piece cuts out
    and you would be listening to a join that does not exist. Every clamp is printed.
  - It does NOT apply the loudness pass. The kit normalises a finished piece as a
    whole, to -14 LUFS, in one measurement over the assembled audio. That changes the
    level of everything together, so it does not change the step at a join, which is
    the thing you are listening for.

--video exports the same joins as a small video, because some cuts fail with the eyes
rather than the ears: a hand mid-gesture, a head that jumps six inches, an eyeline
that swaps sides. The default framing is the 9 by 16 delivery crop at a third of
delivery resolution, taking zoom and focus from the style file if one is named, so a
cut is judged inside the frame that ships. `--frame source` shows the uncropped
picture instead, which is the one to use when checking whether the crop itself is what
broke the cut.

NOTHING HERE IS WELDED TO ANYBODY. No font, no colour, no identifier, no account. It
reads a cut list and a media file, writes audio or video into a folder you choose, and
touches nothing else. It needs ffmpeg and ffprobe, and the Python standard library.
Pillow is deliberately NOT required: this is the step that comes before any caption is
drawn, and a first run should not be blocked on a library it does not use.

Usage (from the kit folder; on Windows write `python` for `python3`):
    python3 bin/hear_joins.py work/rl-cuts.json
    python3 bin/hear_joins.py work/rl-cuts.json --transcript work/rl.srt
    python3 bin/hear_joins.py cuts.json --source footage/take.mov --pad 1.0
    python3 bin/hear_joins.py cuts.json --only P4 --video
    python3 bin/hear_joins.py cuts.json --list          # the table only, no media read
    python3 bin/hear_joins.py cuts.json --all-joins     # including continuous tape

It cannot hear anything either. It makes the listening short enough that a person
will actually do it. That person is the check.
"""

