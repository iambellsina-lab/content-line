def ffmpeg_bin() -> str:
    found = shutil.which("ffmpeg")
    if not found:
        die("ffmpeg is not installed, or not on PATH.\n"
            "  macOS: brew install ffmpeg      Windows: winget install ffmpeg\n"
            "  Debian or Ubuntu: sudo apt install ffmpeg\n"
            "  Then open a NEW terminal window and try again.")
    return found


def ffprobe_bin() -> str:
    found = shutil.which("ffprobe")
    if not found:
        die("ffprobe is not on PATH. It ships with ffmpeg, so an install that has one "
            "and not the other is usually a half unpacked build.")
    return found


_FILTERS: set[str] | None = None


def has_filter(name: str) -> bool:
    global _FILTERS
    if _FILTERS is None:
        out = subprocess.run([ffmpeg_bin(), "-hide_banner", "-filters"],
                             capture_output=True, text=True).stdout
        _FILTERS = {line.split()[1] for line in out.splitlines()
                    if len(line.split()) > 1}
    return name in _FILTERS


def run_ff(cmd: list[str], what: str) -> None:
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        die(f"{what} failed (ffmpeg exit {res.returncode})\n"
            f"{res.stderr.strip()[:2500]}")


def probe_source(path: Path) -> dict:
    """Duration, whether there is audio, and the size as displayed."""
    raw = subprocess.run(
        [ffprobe_bin(), "-v", "error", "-show_entries",
         "format=duration:stream=codec_type,width,height:stream_side_data=rotation",
         "-of", "json", str(path)],
        capture_output=True, text=True)
    if raw.returncode != 0:
        die(f"ffprobe could not read {path}: {raw.stderr.strip()[:300]}")
    info = json.loads(raw.stdout or "{}")
    streams = info.get("streams", [])
    video = next((s for s in streams if s.get("codec_type") == "video"), None)
    rotation = 0
    width = height = 0
    if video:
        for sd in video.get("side_data_list", []) or []:
            if "rotation" in sd:
                rotation = int(sd["rotation"])
        width, height = int(video.get("width", 0)), int(video.get("height", 0))
        if abs(rotation) in (90, 270):      # ffmpeg autorotates, so size as displayed
            width, height = height, width
    return {
        "duration": float(info.get("format", {}).get("duration", 0) or 0),
        "has_audio": any(s.get("codec_type") == "audio" for s in streams),
        "has_video": video is not None,
        "width": width,
        "height": height,
    }


def probe_result(path: Path) -> dict:
    """A file that exists is not an export that worked. Duration and bytes, measured."""
    if not path.exists():
        die(f"{path} was not written, and ffmpeg reported success. Nothing to listen to.")
    size = path.stat().st_size
    if size < 1024:
        die(f"{path} is {size} bytes, which is not audio. Run again with the ffmpeg "
            "output visible to see what it did.")
    raw = subprocess.run([ffprobe_bin(), "-v", "error", "-show_entries",
                          "format=duration", "-of", "csv=p=0", str(path)],
                         capture_output=True, text=True)
    try:
        duration = float((raw.stdout or "0").strip() or 0)
    except ValueError:
        duration = 0.0
    return {"seconds": duration, "bytes": size}


def human_bytes(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024.0
    return f"{n:.1f} GB"


