def read_json(path: Path, what: str):
    try:
        # utf-8-sig so a file saved by Windows Notepad still loads
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except FileNotFoundError:
        die(f"{what} not found: {path}")
    except json.JSONDecodeError as exc:
        die(f"{what} {path} is not valid JSON. Line {exc.lineno}, column {exc.colno}: "
            f"{exc.msg}.\n"
            "  The usual causes: a missing comma between two items, a trailing comma\n"
            "  after the last item, or a straight quote typed as a curly one.")
    return None


def resolve_input(value: str, base: Path) -> Path:
    """Same rule as the rest of the kit: next to the file that names it, then where
    you ran the command from."""
    p = Path(value).expanduser()
    if p.is_absolute():
        return p
    for cand in (base / p, Path.cwd() / p):
        if cand.exists():
            return cand
    return base / p


def slug(name: str, fallback: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", str(name).lower()).strip("-")
    return s or fallback


