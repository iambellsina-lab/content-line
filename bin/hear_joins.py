def plural(n: int, word: str) -> str:
    if n == 1:
        return f"{n} {word}"
    return f"{n} {word[:-1]}ies" if word.endswith("y") else f"{n} {word}s"


def stamp(t: float) -> str:
    m, s = divmod(max(0.0, t), 60)
    return f"{int(m):02d}:{s:05.2f}"


def print_clip(clip: Clip, pad: float) -> None:
    hear = clip.to_hear
    skipped = [j.number for j in clip.joins if j.skip]
    head = (f"{clip.name}  {len(clip.segments)} segments, "
            f"{plural(len(clip.joins), 'join')}, {len(hear)} to hear")
    if skipped:
        head += f", {len(skipped)} skipped ({', '.join(str(n) for n in skipped)})"
    say(head)
    if not clip.joins:
        say("   one continuous segment, so there is no join in this clip")
        return
    for j in clip.joins:
        mark = " - " if j.skip else "   "
        direction = ("continuous tape" if abs(j.gap) <= CONTINUOUS_TOLERANCE
                     else (f"forward {j.gap:.2f}s" if j.gap > 0
                           else f"BACK {abs(j.gap):.2f}s"))
        say(f"{mark}join {j.number:<2}  {stamp(j.out_at)} -> {stamp(j.in_at)}   "
            f"{j.out_at:.2f} -> {j.in_at:.2f}   {direction}"
            f"{'   [skipped]' if j.skip else f'   {j.listen_seconds:.1f}s'}")
        if j.before:
            say(f"            before: {j.before}")
        if j.after:
            say(f"            after:  {j.after}")
        for note in j.notes:
            say(f"            note: {note}")
    total = round(sum(j.listen_seconds for j in hear), 1)
    say(f"   {plural(len(hear), 'join')} to hear, {total:.1f}s of tape at "
        f"{pad:.1f}s either side")


