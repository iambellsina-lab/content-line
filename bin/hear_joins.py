def video_frame(info: dict, frame: str, style: dict) -> tuple[int, int, list[str]]:
    """The picture steps, and the size everything is normalised to.

    "vertical" reproduces the delivery crop at a third of delivery resolution, taking
    zoom and focus from the style file, so a cut is judged inside the frame that
    ships. "source" shows the whole picture, which is what to look at when the
    question is whether the crop broke the cut.
    """
    if frame == "source":
        w, h = info["width"] or 1920, info["height"] or 1080
        if w >= h:
            ow = SOURCE_LONG_SIDE
            oh = max(2, int(round(SOURCE_LONG_SIDE * h / w)) // 2 * 2)
        else:
            oh = SOURCE_LONG_SIDE
            ow = max(2, int(round(SOURCE_LONG_SIDE * w / h)) // 2 * 2)
        return ow, oh, [f"scale={ow}:{oh}:flags=lanczos", "setsar=1",
                        f"fps={VIDEO_FPS}", "format=yuv420p"]
    ow, oh = VERTICAL_W, VERTICAL_H
    zoom = max(1.0, float(style.get("zoom", 1.0) or 1.0))
    fx = min(1.0, max(0.0, float(style.get("focus_x", 0.5) or 0.5)))
    fy = min(1.0, max(0.0, float(style.get("focus_y", 0.5) or 0.5)))
    sw, sh = int(round(ow * zoom)), int(round(oh * zoom))
    return ow, oh, [
        f"scale={sw}:{sh}:force_original_aspect_ratio=increase:flags=lanczos",
        f"crop={ow}:{oh}:x='(iw-ow)*{fx}':y='(ih-oh)*{fy}'",
        "setsar=1", f"fps={VIDEO_FPS}", "format=yuv420p"]


def export_clip(clip: Clip, src: Path, out: Path, markers: dict[int, Path | None],
                want_video: bool, vsteps: list[str], size: tuple[int, int]) -> None:
    """One ffmpeg call per clip: marker, tail, head, marker, tail, head, concatenated.

    The windows are butted with nothing between them, which is what the renderer's
    concat does. The only encode is the output, so the join you hear is the join the
    renderer assembles, one generation later.
    """
    joins = clip.to_hear
    inputs: list[list[str]] = []
    # (video stream, audio stream, exact seconds to keep or None for "all of it")
    parts: list[tuple[str | None, str, float | None]] = []

    def add(args: list[str]) -> int:
        inputs.append(args)
        return len(inputs) - 1

    for j in joins:
        marker = markers.get(j.number)
        if marker is not None:
            if want_video:
                dur = wav_seconds(marker)
                iv = add(["-f", "lavfi", "-t", f"{max(0.1, dur):.3f}", "-i",
                          f"color=c=black:s={size[0]}x{size[1]}:r={VIDEO_FPS}"])
                ia = add(["-i", str(marker)])
                parts.append((f"{iv}:v", f"{ia}:a", None))
            else:
                ia = add(["-i", str(marker)])
                parts.append((None, f"{ia}:a", None))
        for a, b in (j.tail, j.head):
            # -ss before -i so each window seeks. A join at minute 47 of a 2.85 GB
            # file would otherwise decode 47 minutes to reach two seconds.
            #
            # WHY THE LENGTH IS CUT IN THE GRAPH AND NOT BY `-t` ON THE INPUT, measured
            # on this kit's own 420s test file on 2026-10-08 rather than assumed:
            # `-accurate_seek -ss 302.0 -t 2.000` came back with 1.5787 SECONDS, and
            # seven other windows of the same file came back between 1.717 and 2.000.
            # An input `-t` bounds the DEMUXER from wherever the seek actually landed,
            # which is a keyframe before the point asked for, and reading stops when
            # the first stream crosses the limit, so trailing audio packets are lost.
            # A short tail is the worst possible failure here: it silently removes the
            # last fraction of a second before the cut, so the listener hears a join
            # that is not the join. So the input limit is deliberately loose, and the
            # exact window is cut by atrim and trim, which work on decoded frames.
            want = round(b - a, 3)
            i = add(["-accurate_seek", "-ss", f"{a:.3f}",
                     "-t", f"{want + READ_SLACK:.3f}", "-i", str(src)])
            # a:0 explicitly: a phone file can carry an ordinary track and a spatial
            # one, and [i:a] hands over both.
            parts.append((f"{i}:v" if want_video else None, f"{i}:a:0", want))

    chain: list[str] = []
    labels = ""
    for k, (vs, as_, want) in enumerate(parts):
        # Normalise the timestamps to zero FIRST, then cut, then normalise again, so
        # the trim is measured from the point the seek asked for and not from whatever
        # timeline the container happens to carry.
        acut = f"asetpts=PTS-STARTPTS,atrim=0:{want:.3f}," if want else ""
        chain.append(f"[{as_}]{AUDIO_FMT},{acut}asetpts=PTS-STARTPTS[a{k}]")
        if want_video and vs:
            vcut = f"setpts=PTS-STARTPTS,trim=0:{want:.3f}," if want else ""
            chain.append(f"[{vs}]{vcut}" + ",".join(vsteps) + f",setpts=PTS-STARTPTS[v{k}]")
            labels += f"[v{k}][a{k}]"
        else:
            labels += f"[a{k}]"
    if want_video:
        chain.append(f"{labels}concat=n={len(parts)}:v=1:a=1[vout][aout]")
    else:
        chain.append(f"{labels}concat=n={len(parts)}:v=0:a=1[aout]")

    cmd = [ffmpeg_bin(), "-y", "-hide_banner", "-loglevel", "error"]
    for args in inputs:
        cmd += args
    cmd += ["-filter_complex", ";".join(chain)]
    if want_video:
        cmd += ["-map", "[vout]", "-c:v", "libx264", "-preset", "veryfast",
                "-crf", "26", "-pix_fmt", "yuv420p", "-r", str(VIDEO_FPS),
                "-movflags", "+faststart"]
    cmd += ["-map", "[aout]", "-c:a", "aac", "-b:a", AUDIO_BITRATE,
            "-ar", str(SAMPLE_RATE), "-ac", "2", str(out)]
    out.parent.mkdir(parents=True, exist_ok=True)
    run_ff(cmd, f"exporting the joins of {clip.name}")


