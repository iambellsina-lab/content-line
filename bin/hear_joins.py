def _srt_seconds(stamp: str) -> float:
    stamp = stamp.strip().replace(",", ".")
    parts = stamp.split(":")
    try:
        if len(parts) == 3:
            h, m, s = parts
            return int(h) * 3600 + int(m) * 60 + float(s)
        if len(parts) == 2:
            m, s = parts
            return int(m) * 60 + float(s)
        return float(stamp)
    except ValueError:
        return -1.0


def load_transcript(path: Path) -> list[dict]:
    """An .srt, or the .cues.json transcribe.py writes beside it. Either is fine."""
    if path.suffix.lower() == ".json":
        data = read_json(path, "transcript")
        cues = data if isinstance(data, list) else (data or {}).get("cues") or []
        out = []
        for c in cues:
            if isinstance(c, dict) and "start" in c and "end" in c:
                out.append({"start": float(c["start"]), "end": float(c["end"]),
                            "text": str(c.get("text", "")).strip()})
        if not out:
            die(f"{path} holds no cues with start, end and text. transcribe.py writes "
                "NAME.cues.json in that shape, and NAME.srt works here too.")
        return out
    try:
        raw = path.read_text(encoding="utf-8-sig")
    except FileNotFoundError:
        die(f"transcript not found: {path}")
        return []
    cues: list[dict] = []
    for block in re.split(r"\n\s*\n", raw.strip()):
        lines = [ln for ln in block.splitlines() if ln.strip()]
        if not lines:
            continue
        timing = next((ln for ln in lines if "-->" in ln), None)
        if not timing:
            continue
        a, _, b = timing.partition("-->")
        start, end = _srt_seconds(a), _srt_seconds(b)
        if start < 0 or end < 0:
            continue
        text = " ".join(ln.strip() for ln in lines[lines.index(timing) + 1:])
        cues.append({"start": start, "end": end, "text": text.strip()})
    if not cues:
        die(f"{path} does not read as an SRT. Expected blocks of a number, a "
            "`00:00:00,000 --> 00:00:02,000` line, and the text.")
    return cues


def words_before(cues: list[dict], t: float) -> str:
    picked = [c["text"] for c in cues
              if c["end"] > t - TRANSCRIPT_WINDOW and c["start"] < t + 0.01]
    words = " ".join(picked).split()
    if not words:
        return ""
    tail = words[-WORDS_EITHER_SIDE:]
    lead = "..." if len(words) > len(tail) else ""
    return lead + " ".join(tail)


def words_after(cues: list[dict], t: float) -> str:
    picked = [c["text"] for c in cues
              if c["start"] < t + TRANSCRIPT_WINDOW and c["end"] > t - 0.01]
    words = " ".join(picked).split()
    if not words:
        return ""
    head = words[:WORDS_EITHER_SIDE]
    trail = "..." if len(words) > len(head) else ""
    return " ".join(head) + trail


def tail_of(text: str) -> str:
    words = str(text or "").split()
    if not words:
        return ""
    tail = words[-WORDS_EITHER_SIDE:]
    return ("..." if len(words) > len(tail) else "") + " ".join(tail)


def head_of(text: str) -> str:
    words = str(text or "").split()
    if not words:
        return ""
    head = words[:WORDS_EITHER_SIDE]
    return " ".join(head) + ("..." if len(words) > len(head) else "")


